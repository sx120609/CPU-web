import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const require = createRequire(`${root}web/package.json`);
const { build } = require('esbuild');
await build({
  entryPoints: [`${root}harmony/bridge/entry.ts`],
  outfile: `${root}harmony/entry/src/main/resources/rawfile/NativeWebCompatibility.js`,
  bundle: true, format: 'iife', target: 'es2020', minify: true,
  banner: { js: '// Generated by harmony/scripts/build-web-bridge.mjs; shared schedule logic.' },
  alias: { '@': `${root}web/src` },
  plugins: [{ name: 'live-harmony-session', setup(builder) {
    builder.onResolve({ filter: /^(vue|@\/api\/jwxt|@\/stores\/(auth|jwxt)|\.\/clientInfo)$/ },
      () => ({ path: `${root}harmony/bridge/adapters.ts` }));
  } }],
});
